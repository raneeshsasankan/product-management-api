-- 1. Users
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(100) NOT NULL,
                       password_hash VARCHAR(255) NOT NULL,
                       enabled BOOLEAN NOT NULL DEFAULT TRUE,
                       created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX ux_users_normalized_username
    ON users (LOWER(TRIM(username)));


-- 2. Roles
CREATE TABLE roles (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(50) NOT NULL UNIQUE,
                       description VARCHAR(255),
                       created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 3. User-role mapping
CREATE TABLE user_roles (
                            user_id BIGINT NOT NULL,
                            role_id BIGINT NOT NULL,
                            created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            PRIMARY KEY (user_id, role_id),

                            CONSTRAINT fk_user_roles_user
                                FOREIGN KEY (user_id)
                                    REFERENCES users(id)
                                    ON DELETE CASCADE,

                            CONSTRAINT fk_user_roles_role
                                FOREIGN KEY (role_id)
                                    REFERENCES roles(id)
                                    ON DELETE CASCADE
);


-- 4. Permissions
CREATE TABLE permissions (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             name VARCHAR(100) NOT NULL UNIQUE,
                             description VARCHAR(255),
                             created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 5. Role-permission mapping
CREATE TABLE role_permissions (
                                  role_id BIGINT NOT NULL,
                                  permission_id BIGINT NOT NULL,
                                  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                  PRIMARY KEY (role_id, permission_id),

                                  CONSTRAINT fk_role_permissions_role
                                      FOREIGN KEY (role_id)
                                          REFERENCES roles(id)
                                          ON DELETE CASCADE,

                                  CONSTRAINT fk_role_permissions_permission
                                      FOREIGN KEY (permission_id)
                                          REFERENCES permissions(id)
                                          ON DELETE CASCADE
);


-- 6. API permissions
CREATE TABLE api_permissions (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 http_method VARCHAR(10) NOT NULL,
                                 url_pattern VARCHAR(255) NOT NULL,
                                 permission_id BIGINT NOT NULL,
                                 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT fk_api_permissions_permission
                                     FOREIGN KEY (permission_id)
                                         REFERENCES permissions(id),

                                 CONSTRAINT uq_api_permissions_method_pattern
                                     UNIQUE (http_method, url_pattern),

                                 CONSTRAINT chk_api_permissions_method
                                     CHECK (http_method IN (
                                                            'GET', 'POST', 'PUT', 'PATCH', 'DELETE'
                                         ))
);


-- ==========================================
-- 7. Reusable updated_at trigger function
-- ==========================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- ==========================================
-- 8. Automatically update timestamps
-- ==========================================

-- Users
CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();


-- Roles
CREATE TRIGGER trg_roles_updated_at
    BEFORE UPDATE ON roles
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();


-- Permissions
CREATE TRIGGER trg_permissions_updated_at
    BEFORE UPDATE ON permissions
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();


-- API permissions
CREATE TRIGGER trg_api_permissions_updated_at
    BEFORE UPDATE ON api_permissions
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();
